from pyspark.sql.functions import sum, round, col, row_number
from pyspark.sql import Window
import os
# 1. Read Silver dataset
combined_df = spark.read.parquet(
    "/content/output/silver/combined_sales"
)

print("Silver dataset loaded successfully!")
print("Total rows:", combined_df.count())

combined_df.show(5)

# 2. Aggregate sales by store and region
store_sales_qty = combined_df \
    .groupBy("store_id", "store_region") \
    .agg(
        round(sum("total_amount"), 2).alias("total_sales"),
        sum("quantity").alias("total_quantity")
    )

print("Store sales and quantity:")
display(store_sales_qty)
# 3. Rank stores by total sales
store_window = Window.orderBy(
    col("total_sales").desc()
)

store_sales_qty_rank = store_sales_qty.withColumn(
    "rank_store",
    row_number().over(store_window)
)

display(store_sales_qty_rank)

# 4. Find the top 5 stores
top5_store = store_sales_qty_rank.filter(
    col("rank_store") <= 5
)

print("Top 5 Stores:")
display(top5_store)

# 5. Aggregate quantity by product
product_qty = combined_df \
    .groupBy("product_id") \
    .agg(
        sum("quantity").alias("total_quantity")
    )

print("Product quantities:")
display(product_qty)
# 6. Rank products by quantity sold
product_window = Window.orderBy(
    col("total_quantity").desc()
)

product_qty_rank = product_qty.withColumn(
    "rank_product",
    row_number().over(product_window)
)

display(product_qty_rank)
# 7. Find the top 5 products

top5_products = product_qty_rank.filter(
    col("rank_product") <= 5
)

print("Top 5 Products:")
display(top5_products)
# 8. Save Gold outputs as Parquet
gold_path = "/content/output/gold"

os.makedirs(gold_path, exist_ok=True)
# Save top 5 stores
top5_store.write \
    .mode("overwrite") \
    .parquet(gold_path + "/top5_stores")

# Save top 5 products
top5_products.write \
    .mode("overwrite") \
    .parquet(gold_path + "/top5_products")

print("Gold datasets saved successfully!")

